"""Оформление строк отчёта: суммы в рублях и заголовки по ширине."""


def format_kopeks(kopeks: int) -> str:
    """Записывает сумму в копейках как рубли с пробелами между тысячами.

    Args:
        kopeks: сумма в копейках, целое число.

    Returns:
        Строка вида «1 250,00 ₽».
    """
    return f"{kopeks / 100:,.2f} ₽".replace(",", " ").replace(".", ",")


def format_title(text: str, width: int = 40) -> str:
    """Ставит текст по центру строки и заполняет края знаком «=».

    Args:
        text: текст заголовка, обычно с пробелами по краям.
        width: длина итоговой строки в символах.

    Returns:
        Заголовок ровно заданной ширины, если текст не длиннее width.
    """
    return text.center(width, "=")
